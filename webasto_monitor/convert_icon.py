from PIL import Image

# Открываем PNG файл
img = Image.open('webasto.png')

# Конвертируем в ICO формат с ОСНОВНЫМИ размерами Windows
# Используем только проверенные размеры: 16x16, 32x32, 48x48, 256x256
img.save('webasto.ico', format='ICO', sizes=[
    (16, 16),   # Обязательный для контекстного меню
    (32, 32),   # Стандартный размер (самый важный!)
    (48, 48),   # Большой размер
    (256, 256)  # Максимальный размер для современных дисплеев
])

print("Иконка успешно конвертирована в webasto.ico с основными размерами Windows")
